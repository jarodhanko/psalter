import { readdir, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const abcjs = require('abcjs');

const abcDirectory = fileURLToPath(new URL('../src/data/generated/abc/', import.meta.url));
const listMissingTranscripts = process.argv.includes('--list-missing-transcripts');
const files = (await readdir(abcDirectory)).filter((file) => file.endsWith('.ts')).sort();
const missing = [];
const missingUnderlay = [];
// These scores reuse written notes for different text on repeat passes. Their
// note attachments are generated by the viewer's source-guarded alignment maps.
const repeatAwareViewerUnderlay = new Set(['psalter211', 'psalter345']);
const unattachedUnderlay = [];
const mixedLineUnderlay = [];
const partialLineUnderlay = [];
const missingStanzaUnderlay = [];
const missingTranscript = [];
const unevenUnderlayRows = [];
let nextFile = 0;

await Promise.all(Array.from({ length: Math.min(8, files.length) }, async () => {
  while (nextFile < files.length) {
    const file = files[nextFile++];
    const moduleSource = await readFile(join(abcDirectory, file), 'utf8');
    const prefix = 'export default ';
    const line = moduleSource.split('\n').find((candidate) => candidate.startsWith(prefix));
    if (!line?.endsWith(';')) throw new Error(`Unexpected generated ABC module: ${file}`);
    const abc = JSON.parse(line.slice(prefix.length, -1));
    const id = file.slice(0, -3);
    if (!/(^|\n)[wW]:/.test(abc)) missing.push(id);
    if (!/(^|\n)w:/.test(abc)) {
      missingUnderlay.push(id);
    } else {
      if (!/^W:\s*\d+\./m.test(abc)) missingTranscript.push(id);
      const [tune] = abcjs.parseOnly(abc);
      const musicLines = tune.lines.filter((line) => line.staff);
      const lyricCounts = musicLines.map((line) => line.staff.reduce(
        (count, staff) => count + staff.voices.reduce(
          (voiceCount, voice) => voiceCount + voice.filter((event) => event.lyric?.length).length,
          0,
        ),
        0,
      ));
      if (!lyricCounts.some(Boolean)) unattachedUnderlay.push(id);
      if (lyricCounts.length > 1 && lyricCounts.includes(0) && lyricCounts.some(Boolean)) {
        mixedLineUnderlay.push(`${id} (${lyricCounts.join('/')})`);
      }
      const partialLines = musicLines.flatMap((musicLine, index) => {
        const voiceCoverage = musicLine.staff.flatMap((staff) => staff.voices.map((voice) => {
          // A tie continuation sustains the preceding syllable and has no new
          // lyric attack; counting it as uncovered creates false review leads.
          const notes = voice.filter((event) => event.el_type === 'note' && !event.rest
            && !event.pitches?.every((pitch) => pitch.endTie));
          return { total: notes.length, covered: notes.filter((event) => event.lyric?.length).length };
        }));
        const lyricVoice = voiceCoverage.filter(({ covered }) => covered > 0).sort((left, right) => right.covered - left.covered)[0];
        return lyricVoice && lyricVoice.covered < lyricVoice.total
          ? [`${index + 1}:${lyricVoice.covered}/${lyricVoice.total}`]
          : [];
      });
      if (partialLines.length) partialLineUnderlay.push(`${id} (${partialLines.join(',')})`);
      const rowsByLine = musicLines.map((musicLine) => {
        const counts = musicLine.staff.flatMap((staff) => staff.voices.flatMap((voice) =>
          voice.map((event) => event.lyric?.length ?? 0)));
        return Math.max(0, ...counts);
      });
      if (rowsByLine.length > 1 && new Set(rowsByLine).size > 1) {
        unevenUnderlayRows.push(`${id} (${rowsByLine.join('/')})`);
      }
      const printedStanzas = [...abc.matchAll(/^W:\s*(\d+)\./gm)].map((match) => Number(match[1]));
      const underlaidStanzas = new Set([...abc.matchAll(/^w:\s*(\d+)\./gm)].map((match) => Number(match[1])));
      const missingStanzas = [...new Set(printedStanzas)].filter((number) => !underlaidStanzas.has(number));
      if (missingStanzas.length) missingStanzaUnderlay.push(`${id} (${missingStanzas.join(',')})`);
    }
  }
}));

console.log(`Viewer arrangements: ${files.length}; missing ABC lyric fields: ${missing.length}.`);
if (missing.length) console.log(missing.sort((left, right) => left.localeCompare(right, undefined, { numeric: true })).join(', '));
const missingEffectiveUnderlay = missingUnderlay.filter((id) => !repeatAwareViewerUnderlay.has(id));
const mappedRepeatUnderlay = missingUnderlay.filter((id) => repeatAwareViewerUnderlay.has(id));
console.log(`Missing note underlay (native w: or repeat-aware viewer map): ${missingEffectiveUnderlay.length}.`);
if (missingEffectiveUnderlay.length) console.log(missingEffectiveUnderlay.sort((left, right) => left.localeCompare(right, undefined, { numeric: true })).join(', '));
console.log(`Repeat-aware viewer underlay without native w: fields: ${mappedRepeatUnderlay.length}.`);
if (mappedRepeatUnderlay.length) console.log(mappedRepeatUnderlay.sort((left, right) => left.localeCompare(right, undefined, { numeric: true })).join(', '));
console.log(`Review flags, sung w: present but no numbered full W: transcript: ${missingTranscript.length}.`);
if (missingTranscript.length && listMissingTranscripts) console.log(missingTranscript.sort((left, right) => left.localeCompare(right, undefined, { numeric: true })).join(', '));
console.log(`w: present but no ABCJS lyric attachments: ${unattachedUnderlay.length}.`);
if (unattachedUnderlay.length) console.log(unattachedUnderlay.sort((left, right) => left.localeCompare(right, undefined, { numeric: true })).join(', '));
console.log(`Review flags, some music lines untexted while others have lyrics: ${mixedLineUnderlay.length}.`);
if (mixedLineUnderlay.length) console.log(mixedLineUnderlay.sort((left, right) => left.localeCompare(right, undefined, { numeric: true })).join(', '));
console.log(`Review flags, note events within underlaid lines lack lyric slots: ${partialLineUnderlay.length}.`);
if (partialLineUnderlay.length) console.log(partialLineUnderlay.sort((left, right) => left.localeCompare(right, undefined, { numeric: true })).join(', '));
console.log(`Review flags, music lines have different underlay row counts: ${unevenUnderlayRows.length}.`);
if (unevenUnderlayRows.length) console.log(unevenUnderlayRows.sort((left, right) => left.localeCompare(right, undefined, { numeric: true })).join(', '));
console.log(`Review flags, numbered W: stanzas lack numbered w: rows: ${missingStanzaUnderlay.length}.`);
if (missingStanzaUnderlay.length) console.log(missingStanzaUnderlay.sort((left, right) => left.localeCompare(right, undefined, { numeric: true })).join(', '));
